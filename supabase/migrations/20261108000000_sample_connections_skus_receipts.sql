-- Tables behind the Samples-page connections icon, saved OrderStream SKUs, and PO receiving.
-- Already applied to the live project; written here so the repo matches (idempotent).

create table if not exists public.sample_connections (
  style_number text not null,
  system text not null check (system in ('qb', 'ssp', 'orderstream')),
  ref text,
  at timestamptz not null default now(),
  primary key (style_number, system)
);

create table if not exists public.sample_skus (
  vendor_sku text primary key,
  style_number text not null,
  merchant_sku text,
  unit_cost numeric,
  created_at timestamptz not null default now()
);
create index if not exists sample_skus_style_idx on public.sample_skus (style_number);

create table if not exists public.orderstream_receipts (
  id bigint generated by default as identity primary key,
  po_number text not null,
  vendor_sku text not null,
  qty integer not null,
  before_qty integer,
  after_qty integer,
  applied_at timestamptz not null default now()
);
create index if not exists orderstream_receipts_po_idx on public.orderstream_receipts (po_number);

alter table public.sample_connections enable row level security;
alter table public.sample_skus enable row level security;
alter table public.orderstream_receipts enable row level security;

do $$ begin
  if not exists (select 1 from pg_policies where tablename = 'sample_connections' and policyname = 'sample_connections authenticated all') then
    create policy "sample_connections authenticated all" on public.sample_connections for all to authenticated using (true) with check (true);
  end if;
  if not exists (select 1 from pg_policies where tablename = 'sample_skus' and policyname = 'sample_skus authenticated all') then
    create policy "sample_skus authenticated all" on public.sample_skus for all to authenticated using (true) with check (true);
  end if;
  if not exists (select 1 from pg_policies where tablename = 'orderstream_receipts' and policyname = 'orderstream_receipts authenticated all') then
    create policy "orderstream_receipts authenticated all" on public.orderstream_receipts for all to authenticated using (true) with check (true);
  end if;
end $$;
